import { NextResponse } from "next/server";
import { z } from "zod";
import { getViewer } from "@/auth";
import { authorize } from "@/lib/authz/engine";
import { readJsonBody } from "@/lib/body-limit";
import { replaceFiles } from "@/lib/problems/authoring";
import { decodeJudgeFile } from "@/lib/problems/judge-file";
import { rateLimit } from "@/lib/ratelimit";
import { ROUTE_LIMITS } from "@/lib/ratelimit/policy";
import { guardRequest, tooManyRequests } from "@/lib/server/guard";

export const runtime = "nodejs";

/**
 * Upload the judge files of an authored problem.
 *
 * A route rather than a Server Action because the body is a file set, and the
 * action limit is 64 KiB. The proxy's 256 KiB is what bounds it instead, which
 * is ample: what travels here is a script, drivers, a checker and a generator.
 * Test data does not, and is generated by the script from the submission's seed.
 *
 * The upload replaces the whole set. A folder is one thing, and what arrives is
 * all of it; a file that used to be there and is not in the upload is gone.
 */

const ROUTE = "POST /api/admin/problems/[slug]/files";

const MAX_BODY_BYTES = 256 * 1024;

/** Generous for a shell script or a C++ driver, and far short of the body cap. */
const MAX_FILE_BYTES = 64 * 1024;

const uploadSchema = z.object({
  files: z
    .array(
      z.object({
        path: z.string().min(1).max(200),
        content: z.string().min(1).max(MAX_BODY_BYTES),
        encoding: z.literal("base64").optional(),
      }),
    )
    .min(1, "没有收到任何文件")
    .max(200, "一次最多上传 200 个文件"),
});

export async function POST(
  request: Request,
  { params }: { params: Promise<{ slug: string }> },
) {
  const gated = await guardRequest(request, ROUTE);
  if (gated) return gated;

  const viewer = await getViewer();
  if (!authorize("problem.author", null, viewer).allow) {
    return NextResponse.json({ error: "页面不存在" }, { status: 404 });
  }

  const rule = ROUTE_LIMITS[ROUTE];
  const limited = await rateLimit(`author:files:${viewer.uid}`, rule);
  if (!limited.ok) return tooManyRequests(limited.retryAfterMs);

  const { slug } = await params;

  const read = await readJsonBody(request, MAX_BODY_BYTES);
  if (!read.ok) {
    return read.reason === "too-large"
      ? NextResponse.json(
          { error: "上传内容过大；判题文件应当只有几 KB，测试数据请在脚本里现场生成。" },
          { status: 413 },
        )
      : NextResponse.json({ error: "请求体不是合法 JSON" }, { status: 400 });
  }

  const parsed = uploadSchema.safeParse(read.body);
  if (!parsed.success) {
    return NextResponse.json(
      { error: parsed.error.issues[0]?.message ?? "上传内容不合法" },
      { status: 400 },
    );
  }

  const oversized = parsed.data.files.filter(
    (file) => decodeJudgeFile(file).length > MAX_FILE_BYTES,
  );
  if (oversized.length > 0) {
    return NextResponse.json(
      {
        error:
          `${oversized.map((file) => file.path).join("、")} 超过 ${MAX_FILE_BYTES / 1024} KiB；` +
          "判题文件应当只有几 KB。",
      },
      { status: 413 },
    );
  }

  const problems = await replaceFiles(slug, parsed.data.files);
  if (problems.length > 0) {
    return NextResponse.json({ error: problems[0], problems }, { status: 400 });
  }

  return NextResponse.json({ files: parsed.data.files.map((file) => file.path) });
}
